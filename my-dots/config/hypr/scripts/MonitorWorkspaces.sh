#!/usr/bin/env bash
# Per-monitor workspace blocks for Hyprland + Waybar.
#
# Every monitor owns $PER consecutive workspaces, keyed on the Hyprland monitor
# id: monitor 0 (the laptop, eDP-1) gets 1-5, monitor 1 gets 6-10, monitor 2
# gets 11-15, and so on. That is exactly the numbering Waybar derives from
#   "all-outputs": false + "persistent-workspaces": { "*": 5 }
# so the bar on each output shows that monitor's five workspaces and nothing
# else. Hyprland reuses a monitor id per output name, so eDP-1 stays on 1-5.
#
# Usage:
#   MonitorWorkspaces.sh apply              regenerate + apply the rules
#   MonitorWorkspaces.sh watch              apply, then re-apply on monitor hotplug
#   MonitorWorkspaces.sh switch N           focus slot N (1..5) of the focused monitor
#   MonitorWorkspaces.sh move N             move active window to that slot, and follow
#   MonitorWorkspaces.sh movesilent N       move active window to that slot, stay put

set -u

PER=5
GENERATED="$HOME/.config/hypr/UserConfigs/DynamicWorkspaces.conf"

monitors() { hyprctl monitors -j; }

# id -> first workspace of its block
first_of() { echo $(( $1 * PER + 1 )); }

focused_monitor_id() {
	monitors | jq -r 'map(select(.focused)) | .[0].id // 0'
}

generate() {
	local mons
	mons="$(monitors)" || return 1

	{
		echo "# Generated by scripts/MonitorWorkspaces.sh -- do not edit by hand."
		echo "# $PER workspaces per monitor, blocks keyed on the Hyprland monitor id."
		echo
		jq -r --argjson per "$PER" '
			sort_by(.id)[] |
			.id as $id | .name as $name |
			[range($per)] |
			map("workspace = \($id * $per + . + 1), monitor:\($name)"
			    + (if . == 0 then ", default:true" else "" end)) |
			.[]
		' <<<"$mons"
	} > "$GENERATED"

	# Apply live too -- the generated file only takes effect on the next reload.
	while read -r rule; do
		[ -n "$rule" ] && hyprctl keyword workspace "$rule" >/dev/null
	done < <(sed -n 's/^workspace = //p' "$GENERATED")
}

# Drag any already-open workspace back onto the monitor that now owns it.
reflow() {
	local mons total
	mons="$(monitors)"
	total=$(( $(jq 'length' <<<"$mons") * PER ))

	while IFS=$'\t' read -r ws cur; do
		[ -n "${ws:-}" ] || continue
		local owner
		owner="$(jq -r --argjson per "$PER" --argjson ws "$ws" \
			'map(select(.id == (($ws - 1) / $per | floor))) | .[0].name // empty' <<<"$mons")"
		[ -n "$owner" ] && [ "$owner" != "$cur" ] &&
			hyprctl dispatch moveworkspacetomonitor "$ws $owner" >/dev/null
	done < <(hyprctl workspaces -j |
		jq -r --argjson total "$total" \
			'.[] | select(.id >= 1 and .id <= $total) | "\(.id)\t\(.monitor)"')

	# Any monitor left displaying a workspace outside its own block gets shown
	# the first slot of its block instead. Focus is restored afterwards.
	local batch="" back
	back="$(jq -r 'map(select(.focused)) | .[0].name // empty' <<<"$(monitors)")"
	while IFS=$'\t' read -r id name active; do
		local lo=$(( id * PER + 1 )) hi=$(( id * PER + PER ))
		if [ "$active" -lt "$lo" ] || [ "$active" -gt "$hi" ]; then
			batch+="dispatch focusmonitor $name; dispatch workspace $lo; "
		fi
	done < <(monitors | jq -r '.[] | "\(.id)\t\(.name)\t\(.activeWorkspace.id)"')

	if [ -n "$batch" ]; then
		[ -n "$back" ] && batch+="dispatch focusmonitor $back; "
		hyprctl --batch "$batch" >/dev/null
	fi
}

apply() { generate && reflow; }

watch() {
	local sock="${XDG_RUNTIME_DIR}/hypr/${HYPRLAND_INSTANCE_SIGNATURE}/.socket2.sock"
	apply
	socat -U - "UNIX-CONNECT:$sock" | while read -r line; do
		case "$line" in
			monitoradded*|monitorremoved*) sleep 1; apply ;;
		esac
	done
}

slot_target() {
	local slot="$1"
	case "$slot" in
		[1-9]|[1-9][0-9]) ;;
		*) exit 1 ;;
	esac
	[ "$slot" -le "$PER" ] || exit 1
	echo $(( $(focused_monitor_id) * PER + slot ))
}

case "${1:-apply}" in
	apply)      apply ;;
	watch)      watch ;;
	switch)     hyprctl dispatch workspace "$(slot_target "${2:-}")" ;;
	move)       hyprctl dispatch movetoworkspace "$(slot_target "${2:-}")" ;;
	movesilent) hyprctl dispatch movetoworkspacesilent "$(slot_target "${2:-}")" ;;
	*)          echo "usage: ${0##*/} {apply|watch|switch N|move N|movesilent N}" >&2; exit 2 ;;
esac
